class Target:
    def __init__(self, driver, cc=None, arch=DEFAULT_ARCH, brands=None, label=None, provenance=None):
        self.driver, self.cc, self.arch = driver, cc, arch
        self.brands = list(brands or [])
        self.label = label or "/".join([driver] + ([cc] if cc else []) +
                                       ([arch] if arch != DEFAULT_ARCH else []))
        self.provenance = provenance
        self.branch = driver.split(".")[0]
        self.max_cuda = DRIVER_MAX_CUDA.get(self.branch)

    def as_dict(self):
        return {"label": self.label, "driver": self.driver, "branch": self.branch, "cc": self.cc,
                "arch": self.arch, "brands": self.brands, "max_cuda": self.max_cuda,
                "provenance": self.provenance}


def parse_target(spec):
    """[LABEL=]DRIVER[/CC[/ARCH[/BRAND,BRAND]]] — empty fields allowed as 550//arm64."""
    label = None
    if "=" in spec:
        label, spec = spec.split("=", 1)
    parts = [p.strip() for p in spec.split("/")]
    if not parts[0]:
        raise Refused(f"target '{spec}' declares no driver version")
    get = lambda i: parts[i] if len(parts) > i and parts[i] else None
    brands = [b.strip() for b in (get(3) or "").split(",") if b.strip()]
    return Target(parts[0], get(1), (get(2) or DEFAULT_ARCH).replace("linux/", ""), brands, label)


def target_from_node_labels(labels, node_name="node"):
    """Pure: node labels -> Target. Refuses on missing or contradictory facts."""
    observed = next(((k, labels[k]) for k in GFD_DRIVER_LABELS if labels.get(k)), None)
    declared = labels.get(DECLARED_DRIVER_LABEL)
    if observed and declared and observed[1].split(".")[0] != declared:
        raise Refused(
            f"node {node_name} contradicts itself: observed {observed[0]}={observed[1]} "
            f"but declared {DECLARED_DRIVER_LABEL}={declared}. A node whose own facts "
            f"disagree cannot ground a verdict — fix the declaration (the drift audit "
            f"owns this class of finding) or pass --target explicitly.")
    source = observed or ((DECLARED_DRIVER_LABEL, declared) if declared else None)
    if not source:
        raise Refused(
            f"node {node_name} declares no driver fact "
            f"({', '.join(GFD_DRIVER_LABELS + (DECLARED_DRIVER_LABEL,))}) — "
            f"cannot verify; pass --target explicitly if you know the branch.")
    major, minor = labels.get("nvidia.com/gpu.compute.major"), labels.get("nvidia.com/gpu.compute.minor")
    cc = f"{major}.{minor}" if major and minor else None
    arch = labels.get("kubernetes.io/arch") or DEFAULT_ARCH
    prov = f"{source[0]}={source[1]}" + (f", nvidia.com/gpu.compute.*={cc}" if cc else
                                         ", no GFD compute-capability labels (arch axis undecided)")
    return Target(source[1], cc, arch, brands=None, label=node_name, provenance=prov)


def node_labels(spec):
    """--from-node [context/]node — the only step that touches a cluster."""
    context, _, name = spec.rpartition("/")
    cmd = ["kubectl"] + (["--context", context] if context else []) + \
          ["get", "node", name, "-o", "json"]
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=60, check=True).stdout
    except (OSError, subprocess.SubprocessError) as e:
        stderr = getattr(e, "stderr", "") or str(e)
        raise Refused(f"could not read node '{spec}': {stderr.strip()}")
    return json.loads(out).get("metadata", {}).get("labels", {}), name


