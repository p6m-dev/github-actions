def vtuple(s):
    return tuple(int(x) for x in re.findall(r"\d+", s)[:3]) or (0,)


def split_arch_entry(entry):
    """'12.0a+PTX' -> ('12.0', 'a', True).

    CUDA 12.8 added arch-accelerated targets (sm_100a, sm_120a) and 12.9 added
    family-specific ones (sm_100f). The suffix marks EXTRA instructions compiled
    in for that exact architecture — Blackwell's tcgen05 tensor-core ops and the
    NVFP4/MXFP6 datatypes among them — so '12.0a' covers compute capability 12.0
    and then some. Reading the suffix as part of the number makes a correctly
    built Blackwell image look uncompiled.
    """
    ptx = entry.endswith("+PTX")
    base = entry[:-4] if ptx else entry
    suffix = ""
    if base and base[-1] in ("a", "f"):
        base, suffix = base[:-1], base[-1]
    return base, suffix, ptx


def check_arch(arch_list, cc):
    entries = [e for e in re.split(r"[;,\s]+", arch_list.strip()) if e]
    parsed = [split_arch_entry(e) for e in entries]

    for base, suffix, _ in parsed:
        if base == cc:
            extra = {"a": " (arch-accelerated target — the Blackwell-class instructions "
                          "and datatypes are compiled in)",
                     "f": " (family-specific target)"}.get(suffix, "")
            return True, f"compute capability {cc} in TORCH_CUDA_ARCH_LIST ({arch_list}){extra}"

    # PTX is JIT-forward-compatible, but ONLY to generic instructions: arch-
    # accelerated ops cannot be JIT'd from generic PTX at all. On Blackwell that
    # makes "works via PTX" mean "runs without the hardware you paid for".
    ptx = [base for base, _, is_ptx in parsed if is_ptx]
    if ptx and any(vtuple(p) <= vtuple(cc) for p in ptx):
        return True, (f"{cc} not compiled, but PTX from {max(ptx, key=vtuple)} JIT-forward-compatible "
                      f"({arch_list}) — first launch is slow, not guaranteed for all kernels, and no "
                      f"arch-accelerated instruction can be reached this way")
    return False, f"compute capability {cc} not in TORCH_CUDA_ARCH_LIST ({arch_list}), no applicable +PTX"


def verdict_for_platform(env, target):
    """-> (worst, findings, basis). 0 compatible, 1 incompatible, 2 cannot-verify."""
    status, findings, basis = evaluate_requirements(env, target)
    worst = {SATISFIED: 0, UNSATISFIED: 1, UNDECIDED: 2, MALFORMED: 1}[status]
    if status == MALFORMED:
        findings.append(("requirement expression", False,
                         "libnvidia-container refuses a malformed expression outright — "
                         "the container will not start"))

    # Not enforced at container start: this axis decides whether compiled kernels
    # exist once it is running (a YP6M-3505-class failure), so it is reported
    # separately and never confused with the driver check.
    arch = env.get("TORCH_CUDA_ARCH_LIST")
    if target.cc:
        if arch:
            ok, detail = check_arch(arch, target.cc)
            findings.append(("TORCH_CUDA_ARCH_LIST vs cc (not enforced at start; decides kernel fit)",
                             ok, detail))
            if not ok:
                # A settled arch mismatch is a definite refusal; it must not be
                # reported as merely unverified just because the driver axis was.
                worst = worse(worst, 1)
        else:
            findings.append(("TORCH_CUDA_ARCH_LIST", None,
                             f"kernel fit for compute capability {target.cc} unverified: the "
                             f"image declares no TORCH_CUDA_ARCH_LIST"))
    return worst, findings, basis


def evaluate(image, platforms, index_digest, target):
    """One image against one target -> a result dict (JSON-shaped)."""
    if not target.max_cuda:
        return {"image": image, "digest": index_digest, "target": target.as_dict(),
                "verdict": LABELS[2], "exit": 2, "platforms": [],
                "refusal": f"driver branch '{target.branch}' is not in the known table "
                           f"({', '.join(sorted(DRIVER_MAX_CUDA))}) — add it deliberately, never guess"}

    entries, worst, targeted_any, basis = [], 0, False, None
    for p in platforms:
        targeted = p["arch"] is None or p["arch"] == target.arch
        w, findings, b = verdict_for_platform(p["env"], target)
        entries.append({
            "platform": p["platform"], "digest": p["digest"], "targeted": targeted,
            "verdict": LABELS[w], "basis": b,
            "findings": [{"check": n, "status": {True: "ok", False: "fail", None: "unknown"}[o],
                          "detail": d} for n, o, d in findings]})
        if targeted:
            targeted_any = True
            worst = worse(worst, w)
            basis = basis or b

    result = {"image": image, "digest": index_digest, "target": target.as_dict(),
              "platforms": entries, "basis": basis}
    if not targeted_any:
        result.update({"verdict": LABELS[2], "exit": 2,
                       "refusal": f"image publishes no linux/{target.arch} variant "
                                  f"(has: {', '.join(p['platform'] for p in platforms)}) — "
                                  f"cannot verify what would run on this target"})
    else:
        result.update({"verdict": LABELS[worst], "exit": worst})
    return result


