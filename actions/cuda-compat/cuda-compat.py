#!/usr/bin/env python3
"""cuda-compat: will this image's CUDA userspace run on a node with this driver?

Answers the question nvidia-container-cli answers at container start, without a
node: it evaluates the image's NVIDIA_REQUIRE_* expressions against a stated set
of node facts, using a faithful port of libnvidia-container's own DSL evaluator
(src/cli/dsl.c: dsl_evaluate / dsl_compare_version / dsl_compare_string, plus the
four rules src/cli/configure.c registers). tests/oracle/ holds a golden table
generated by compiling that C code verbatim; test_dsl_parity.py fails if this
port and NVIDIA's code ever disagree.

  space-separated constraints are ORed, comma-separated constraints are ANDed
  (NVIDIA container-toolkit docs; dsl_evaluate confirms it)

That is why an image whose first term reads cuda>=13.0 can still run on driver
550: the later brand=tesla,driver>=550,driver<551 term is an OR branch, put
there by NVIDIA's base image to declare the driver branches its bundled
cuda-compat package supports. Reading those terms as AND-noise is the difference
between "INCOMPATIBLE" and "COMPATIBLE via forward compatibility", so verdicts
name which term carried them.

Verdicts, per image per target class per platform:

  COMPATIBLE      + basis: native CUDA match, or a forward-compat branch term
  INCOMPATIBLE    the container is refused at start; the message an operator
                  would see in the kubelet log is quoted verbatim
  CANNOT-VERIFY   a fact is missing, or the image declares no CUDA metadata.
                  Never a silent pass.

Facts are three-valued: a missing brand or compute capability makes the terms
that need it UNDECIDED, never assumed-true. A verdict is only issued when it
holds for every value the missing fact could take.

Usage:
  cuda-compat.py IMAGE [IMAGE ...] --target 550.144.03/7.5/amd64/Tesla [--json]
  cuda-compat.py IMAGE --driver 550 --cc 7.5          # single-target shorthand
  cuda-compat.py IMAGE --from-node ctx/node           # read the facts off a node

Target syntax: [LABEL=]DRIVER[/CC[/PLATFORM-ARCH[/BRAND[,BRAND...]]]]
  DRIVER         full version (550.144.03) when known — a bare branch (550)
                 cannot decide terms that compare against a finer version, and
                 says so instead of guessing
  CC             GPU compute capability, e.g. 7.5 — NVIDIA's "arch" property
  PLATFORM-ARCH  which image variant runs here (default amd64). Other variants
                 are reported but never vote: an arm64 child cannot run on an
                 amd64 node.
  BRAND          NVML brand(s) the GPU may report, e.g. Tesla,Nvidia. Datacenter
                 SKUs report different values across driver branches, so a set is
                 allowed; the verdict must hold for all of them.

Exit codes: 0 compatible, 1 incompatible, 2 cannot-verify — ALWAYS, so the
signal is never lost. Consumers choose their own strictness (the composite
action's strict-unknown input decides whether exit 2 fails the step).

Assurance tier: static analysis of image config + the runtime's own requirement
logic. It says "the driver check will/will not refuse this container", not
"boots". It cannot see whether the bundled compat libraries are intact, and a
runtime configured for CDI, or an image setting NVIDIA_DISABLE_REQUIRE, skips
the requirement check altogether — both are reported when detected.

Stdlib only, anonymous registry auth only. Registry credentials belong in the
action wrapper, never here (YP6M-3480) — this file must stay runnable by a
customer with nothing but python3.
"""
