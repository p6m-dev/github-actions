def parse_ref(ref):
    # [registry/]repo[:tag][@digest]
    digest = None
    if "@" in ref:
        ref, digest = ref.split("@", 1)
    tag = "latest"
    if ":" in ref.rsplit("/", 1)[-1]:
        ref, tag = ref.rsplit(":", 1)
    parts = ref.split("/")
    if "." in parts[0] or ":" in parts[0] or parts[0] == "localhost":
        registry, repo = parts[0], "/".join(parts[1:])
    else:
        registry, repo = "registry-1.docker.io", ref if "/" in ref else f"library/{ref}"
    return registry, repo, (digest or tag)


class Registry:
    def __init__(self, registry, repo):
        self.base = f"https://{registry}/v2/{repo}"
        self.repo = repo
        self.token = None

    def _get(self, url, accept, _retried=False):
        req = urllib.request.Request(url, headers={"Accept": accept})
        if self.token:
            req.add_header("Authorization", f"Bearer {self.token}")
        try:
            resp = urllib.request.urlopen(req, timeout=30)
            return resp.read(), resp.headers  # case-insensitive Message, not a dict
        except urllib.error.HTTPError as e:
            if e.code != 401 or self.token:
                raise
            if _retried:
                raise Refused(f"{url}: registry kept answering 401 after a token exchange")
            challenge = e.headers.get("WWW-Authenticate", "")
            m = dict(re.findall(r'(\w+)="([^"]*)"', challenge))
            if "realm" not in m:
                raise
            # The realm comes from the registry, i.e. from whoever we are asking
            # about. It must not be able to send us somewhere else in plaintext.
            realm = urllib.parse.urlsplit(m["realm"])
            if realm.scheme != "https" or not realm.hostname:
                raise Refused(f"registry offered a non-https auth realm: {m['realm']}")
            q = {"service": m.get("service", ""), "scope": m.get("scope", f"repository:{self.repo}:pull")}
            tok = json.loads(urllib.request.urlopen(
                f"{m['realm']}?{urllib.parse.urlencode(q)}", timeout=30).read())
            self.token = tok.get("token") or tok.get("access_token")
            if not self.token:
                raise Refused("token endpoint returned neither token nor access_token")
            return self._get(url, accept, _retried=True)

    def manifest(self, ref):
        body, headers = self._get(f"{self.base}/manifests/{ref}", ACCEPT)
        digest = headers.get("Docker-Content-Digest")
        # Registry-controlled text that we print, and that the action forwards
        # into $GITHUB_OUTPUT and issue bodies. Accept only the shape it claims.
        if digest and not re.fullmatch(r"[a-z0-9]+:[a-f0-9]{32,128}", digest):
            digest = None
        return json.loads(body), digest

    def blob(self, digest):
        body, _ = self._get(f"{self.base}/blobs/{digest}", "*/*")
        return json.loads(body)


def env_map(config):
    out = {}
    for e in (config.get("config") or {}).get("Env") or []:
        k, _, v = e.partition("=")
        out[k] = v
    return out


def fetch_platforms(image):
    """-> (index_digest, [{platform, arch, digest, env}]) — every linux child, once."""
    registry, repo, ref = parse_ref(image)
    reg = Registry(registry, repo)
    top, top_digest = reg.manifest(ref)
    resolved = top_digest or (ref if ref.startswith("sha256:") else None)

    out = []
    if top.get("mediaType") in MEDIA_INDEX or "manifests" in top:
        for m in top["manifests"]:
            p = m.get("platform") or {}
            # attestation manifests ride in the index as unknown/unknown children
            if p.get("os") != "linux" or m.get("annotations", {}).get("vnd.docker.reference.type"):
                continue
            man, _ = reg.manifest(m["digest"])
            out.append({"platform": f"linux/{p.get('architecture')}",
                        "arch": p.get("architecture"),
                        "digest": m["digest"],
                        "env": env_map(reg.blob(man["config"]["digest"]))})
    else:
        # No index: the config blob is the only place the arch is stated.
        cfg = reg.blob(top["config"]["digest"])
        arch = cfg.get("architecture")
        out.append({"platform": f"{cfg.get('os', 'linux')}/{arch or 'unknown-arch'}",
                    "arch": arch, "digest": resolved, "env": env_map(cfg)})
    if not out:
        raise Refused(f"{image}: index declares no linux platform manifests")
    return resolved, out


