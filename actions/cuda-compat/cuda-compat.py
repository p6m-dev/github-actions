def collect_requirements(env):
    """Mirror of nvidia-container-toolkit CUDA.GetRequirements().

    Every NVIDIA_REQUIRE_* var (except JETPACK) is passed to nvidia-container-cli
    as its own --require and they are ANDed. A "legacy" image — CUDA_VERSION set
    and no NVIDIA_REQUIRE_CUDA — has cuda>=<major.minor> synthesized for it, so
    CUDA_VERSION is enforced in exactly that case and inert otherwise.
    """
    if str(env.get("NVIDIA_DISABLE_REQUIRE", "")).lower() in ("1", "true", "t", "yes"):
        return [], "NVIDIA_DISABLE_REQUIRE is set — the runtime skips every requirement check"
    reqs = [(k, v) for k, v in sorted(env.items())
            if k.startswith("NVIDIA_REQUIRE_") and not k.startswith("NVIDIA_REQUIRE_JETPACK") and v]
    # IsLegacy() reads ONLY NVIDIA_REQUIRE_CUDA, and GetRequirements APPENDS the
    # synthesized constraint. Gating on "no NVIDIA_REQUIRE_* at all", or replacing
    # rather than appending, drops a conjunct the runtime enforces — and dropping
    # a conjunct can only ever make this tool more permissive than the runtime.
    if not env.get("NVIDIA_REQUIRE_CUDA") and env.get("CUDA_VERSION"):
        m = re.match(r"v?(\d+)\.(\d+)", env["CUDA_VERSION"])
        if m:
            reqs.append(("CUDA_VERSION (legacy image — the runtime synthesizes this requirement)",
                         f"cuda>={m.group(1)}.{m.group(2)}"))
    return reqs, None


def evaluate_requirements(env, target):
    """-> (status, findings, basis). Unanimous across every brand the GPU may report."""
    reqs, skipped = collect_requirements(env)
    if skipped:
        return UNDECIDED, [("requirement check", None, skipped +
                            " — the container starts, but nothing verified its CUDA fitness")], None
    if not reqs:
        return UNDECIDED, [("CUDA metadata", None,
                            "image declares neither NVIDIA_REQUIRE_* nor CUDA_VERSION — cannot "
                            "verify; consider a p6m.dev/cuda-requires annotation")], None

    brands = target.brands or list(NVML_BRANDS)
    per_brand = {}
    for brand in brands:
        facts = {"cuda": target.max_cuda, "driver": target.driver,
                 "arch": target.cc, "brand": brand}
        results = []
        for name, expr in reqs:
            try:
                results.append((name, expr, eval_expression(expr, facts)))
            except Refused as e:
                results.append((name, expr, {"status": MALFORMED, "detail": str(e)}))
        per_brand[brand] = results

    statuses = {b: combine(r) for b, r in per_brand.items()}
    unanimous = set(statuses.values())
    probe = brands[0]
    findings, basis = [], None
    for name, expr, res in per_brand[probe]:
        if res["status"] == SATISFIED:
            basis = ("native CUDA-version match" if res["keys"] == ["cuda"] else
                     f"driver-branch allowance '{res['term']}' — CUDA forward compatibility: the "
                     f"image ships a cuda-compat runtime declaring support for this branch "
                     f"(NVIDIA supports this on datacenter GPUs only)")
            findings.append((f"{name} (enforced at container start)", True,
                             f"satisfied by term #{res['term_index'] + 1} '{res['term']}': {res['detail']}"))
        elif res["status"] == UNSATISFIED:
            findings.append((f"{name} (enforced at container start)", False,
                             f"container refused at start — \"{res['message']}\""))
        elif res["status"] == MALFORMED:
            findings.append((f"{name}", None, res["detail"]))
        else:
            findings.append((f"{name} (enforced at container start)", None,
                             f"undecided: {res['detail']}"))

    if len(unanimous) > 1:
        deciding = sorted(f"{b}={s}" for b, s in statuses.items())
        return UNDECIDED, findings + [
            ("GPU brand", None, "verdict depends on which brand the GPU reports "
                                f"({', '.join(deciding[:6])}{'...' if len(deciding) > 6 else ''}) — "
                                "declare the brand on the target to decide")], basis
    return unanimous.pop(), findings, basis


def combine(results):
    """AND across the image's separate NVIDIA_REQUIRE_* variables."""
    order = [r["status"] for _, _, r in results]
    for bad in (MALFORMED, UNSATISFIED, UNDECIDED):
        if bad in order:
            return bad
    return SATISFIED


