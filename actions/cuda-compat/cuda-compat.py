MARK = {"ok": "ok  ", "fail": "FAIL", "unknown": "?   "}


def print_text(report):
    for r in report["results"]:
        t = r["target"]
        print(f"\nimage:  {r['image']}" + (f"\n        {r['digest']}" if r["digest"] else ""))
        prov = f"  [{t['provenance']}]" if t.get("provenance") else ""
        print(f"target: {t['label']} — driver {t['driver']}"
              + (f" (reports CUDA {t['max_cuda']})" if t["max_cuda"] else " (UNKNOWN BRANCH)")
              + (f", compute capability {t['cc']}" if t["cc"] else "")
              + (f", brand {'|'.join(t['brands'])}" if t["brands"] else "")
              + f", linux/{t['arch']}{prov}")
        if r.get("refusal"):
            print(f"  CANNOT-VERIFY: {r['refusal']}")
        for p in r["platforms"]:
            scope = "" if p["targeted"] else "  (not targeted — informational)"
            print(f"\n  {p['platform']}: {p['verdict']}{scope}")
            for f in p["findings"]:
                print(f"    [{MARK[f['status']]}] {f['check']}: {f['detail']}")
        print(f"\n  => {r['image']} on {t['label']}: {r['verdict']}"
              + (f"\n     basis: {r['basis']}" if r.get("basis") else ""))
    print(f"\nverdict: {report['verdict']}\nassurance: {report['assurance']}")


def main():
    ap = argparse.ArgumentParser(
        description="Static CUDA compatibility verdict for container images against driver/GPU targets.")
    ap.add_argument("images", nargs="+", metavar="IMAGE")
    ap.add_argument("--target", action="append", default=[],
                    metavar="[LABEL=]DRIVER[/CC[/ARCH[/BRAND]]]",
                    help="repeatable target class, e.g. playground-t4=550.144.03/7.5/amd64/Tesla")
    ap.add_argument("--driver", help="single-target shorthand: driver version or branch, e.g. 550")
    ap.add_argument("--cc", help="single-target shorthand: compute capability, e.g. 7.5")
    ap.add_argument("--brand", help="single-target shorthand: NVML brand(s), e.g. Tesla,Nvidia")
    ap.add_argument("--arch", default=DEFAULT_ARCH, help=f"image arch for --driver (default {DEFAULT_ARCH})")
    ap.add_argument("--from-node", metavar="[CONTEXT/]NODE",
                    help="derive a target from a live node's labels (needs kubectl)")
    ap.add_argument("--json", action="store_true", help="machine-readable report on stdout")
    args = ap.parse_args()

    targets = []
    try:
        targets += [parse_target(s) for s in args.target]
        if args.driver:
            targets.append(Target(args.driver, args.cc, args.arch.replace("linux/", ""),
                                  [b.strip() for b in (args.brand or "").split(",") if b.strip()]))
        elif args.cc or args.brand:
            raise Refused("--cc/--brand without --driver: not a target on their own")
        if args.from_node:
            labels, name = node_labels(args.from_node)
            targets.append(target_from_node_labels(labels, name))
    except Refused as e:
        print(f"CANNOT-VERIFY: {e}", file=sys.stderr)
        sys.exit(2)

    if not targets:
        ap.error("no target given: use --target, --driver, or --from-node")

    results = []
    for image in args.images:
        try:
            index_digest, platforms = fetch_platforms(image)
        except (Refused, urllib.error.URLError, urllib.error.HTTPError,
                OSError, KeyError, ValueError) as e:
            for t in targets:
                results.append({"image": image, "digest": None, "target": t.as_dict(),
                                "verdict": LABELS[2], "exit": 2, "platforms": [],
                                "refusal": f"could not read image metadata: {e}"})
            continue
        results.extend(evaluate(image, platforms, index_digest, t) for t in targets)

    overall = worst((r["exit"] for r in results), default=2)
    report = {"schema": SCHEMA, "assurance": ASSURANCE, "verdict": LABELS[overall],
              "exit": overall, "results": results}
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        print_text(report)
    sys.exit(overall)


if __name__ == "__main__":
    main()
